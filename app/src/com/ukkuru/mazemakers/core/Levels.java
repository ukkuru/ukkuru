    public static Maze[] all() {
        Maze[] out = new Maze[DATA.length];
        for (int i = 0; i < DATA.length; i++) {
            String[] d = DATA[i];
            String[] rows = new String[d.length - 3];
            System.arraycopy(d, 3, rows, 0, rows.length);
            out[i] = Maze.parse(d[0], d[1], STUDIO, Integer.parseInt(d[2]), rows);
        }
        return out;
    }

